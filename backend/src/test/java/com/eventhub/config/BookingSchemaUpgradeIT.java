package com.eventhub.config;

import static org.junit.jupiter.api.Assertions.*;

import com.eventhub.dto.ApiDtos;
import com.eventhub.repository.RegistrationRepository;
import com.eventhub.service.EventService;
import java.sql.DriverManager;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.test.context.ActiveProfiles;
import org.springframework.test.context.DynamicPropertyRegistry;
import org.springframework.test.context.DynamicPropertySource;

/** Starts from the original schema, not Hibernate's newly generated schema. */
@SpringBootTest
@ActiveProfiles("test")
class BookingSchemaUpgradeIT {

    @DynamicPropertySource
    static void legacyDatabase(DynamicPropertyRegistry registry)
        throws Exception {
        String url = "jdbc:h2:mem:booking_legacy_upgrade;DB_CLOSE_DELAY=-1";
        try (
            var connection = DriverManager.getConnection(url, "sa", "");
            var sql = connection.createStatement()
        ) {
            sql.execute(
                "create table users(id bigint generated by default as identity primary key,email varchar(255) not null unique,password varchar(255) not null,name varchar(255) not null,role varchar(255) not null)"
            );
            sql.execute(
                "create table events(id bigint generated by default as identity primary key,title varchar(255),description varchar(2000),location varchar(255),starts_at timestamp,capacity integer,category varchar(255),image_url varchar(2000))"
            );
            sql.execute(
                "create table ticket_types(id bigint generated by default as identity primary key,event_id bigint,name varchar(80),description varchar(1000),price numeric(12,2),capacity integer)"
            );
            sql.execute(
                "create table registrations(id bigint generated by default as identity primary key,user_id bigint not null,event_id bigint not null,ticket_type_id bigint,registered_at timestamp not null,quantity integer,ticket_code varchar(32) not null unique,checked_in_at timestamp,constraint uk_registration_user_event unique(user_id,event_id))"
            );
            sql.execute(
                "insert into users(email,password,name,role) values('legacy@example.test','test-hash','Legacy User','USER')"
            );
            sql.execute(
                "insert into events(title,description,location,starts_at,capacity,category) values('Legacy Event','Old data','Bangkok','2035-01-01 10:00:00',10,'TECH')"
            );
            sql.execute(
                "insert into ticket_types(event_id,name,price,capacity) values(1,'Free',0,10)"
            );
            sql.execute(
                "insert into registrations(user_id,event_id,ticket_type_id,registered_at,quantity,ticket_code) values(1,1,1,current_timestamp,2,'LEGACY-TICKET')"
            );
        }
        registry.add("spring.datasource.url", () -> url);
        registry.add("spring.jpa.hibernate.ddl-auto", () -> "update");
    }

    @Autowired
    RegistrationRepository registrations;

    @Autowired
    EventService events;

    @Test
    void originalDataSurvivesAndCanceledUserCanBookAgain() {
        var old = registrations.findByTicketCode("LEGACY-TICKET").orElseThrow();
        assertEquals("CONFIRMED", old.getStatus());
        assertEquals(2, old.getQuantity());
        assertNotNull(old.getPurchasedUnitPrice());
        events.cancel(1L, () -> "legacy@example.test", "เปลี่ยนแผน");
        events.register(1L, new ApiDtos.PurchaseRequest(1L, 3), () ->
            "legacy@example.test"
        );
        assertEquals(2, registrations.count());
        assertEquals(3, registrations.seatsReservedByEventId(1L));
        assertEquals(
            "CANCELLED",
            registrations
                .findByTicketCode("LEGACY-TICKET")
                .orElseThrow()
                .getStatus()
        );
    }
}
