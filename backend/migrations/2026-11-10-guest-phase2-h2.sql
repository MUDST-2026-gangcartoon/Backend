-- Apply to an existing EventHub H2 database before starting the Phase 2
-- Backend with ddl-auto=validate. Existing member rows are preserved.

CREATE TABLE IF NOT EXISTS guest_identities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    normalized_email VARCHAR(254) NOT NULL UNIQUE,
    claimed_user_id BIGINT
);

CREATE TABLE IF NOT EXISTS guest_email_verifications (
    user_id BIGINT PRIMARY KEY,
    email VARCHAR(254) NOT NULL,
    code_hash VARCHAR(72),
    expires_at TIMESTAMP(6) NOT NULL,
    resend_at TIMESTAMP(6) NOT NULL,
    failed_attempts INTEGER NOT NULL,
    verified_at TIMESTAMP(6)
);

CREATE TABLE IF NOT EXISTS registration_attempts (
    id UUID PRIMARY KEY,
    version BIGINT,
    event_id BIGINT NOT NULL,
    owner_key VARCHAR(66) NOT NULL,
    started_at TIMESTAMP(6) NOT NULL,
    confirmed_at TIMESTAMP(6),
    registration_id BIGINT
);

CREATE INDEX IF NOT EXISTS idx_registration_attempts_event_started
    ON registration_attempts(event_id, started_at);

ALTER TABLE registrations ADD COLUMN IF NOT EXISTS active_guest_id BIGINT;
ALTER TABLE registrations ADD COLUMN IF NOT EXISTS guest_id BIGINT;
ALTER TABLE registrations ADD COLUMN IF NOT EXISTS guest_display_name VARCHAR(120);
ALTER TABLE registrations ADD COLUMN IF NOT EXISTS guest_session_hash VARCHAR(64);
ALTER TABLE registrations ADD COLUMN IF NOT EXISTS guest_request_key VARCHAR(128);
ALTER TABLE registrations ADD COLUMN IF NOT EXISTS guest_attempt_id UUID;
ALTER TABLE registrations ADD CONSTRAINT IF NOT EXISTS fk_registrations_guest
    FOREIGN KEY (guest_id) REFERENCES guest_identities(id);
ALTER TABLE registrations ADD CONSTRAINT IF NOT EXISTS ck_registration_owner
    CHECK ((user_id IS NOT NULL AND guest_id IS NULL) OR (user_id IS NULL AND guest_id IS NOT NULL));
ALTER TABLE registrations ADD CONSTRAINT IF NOT EXISTS uk_active_registration_guest_event
    UNIQUE (active_guest_id, event_id);
ALTER TABLE registrations ADD CONSTRAINT IF NOT EXISTS uk_guest_registration_replay
    UNIQUE (guest_session_hash, event_id, guest_request_key);
ALTER TABLE registrations ALTER COLUMN user_id DROP NOT NULL;

ALTER TABLE mock_payment_orders ADD COLUMN IF NOT EXISTS guest_id BIGINT;
ALTER TABLE mock_payment_orders ADD COLUMN IF NOT EXISTS guest_display_name VARCHAR(120);
ALTER TABLE mock_payment_orders ADD COLUMN IF NOT EXISTS guest_session_hash VARCHAR(64);
ALTER TABLE mock_payment_orders ADD COLUMN IF NOT EXISTS guest_request_key VARCHAR(128);
ALTER TABLE mock_payment_orders ADD COLUMN IF NOT EXISTS registration_attempt_id UUID;
ALTER TABLE mock_payment_orders ADD CONSTRAINT IF NOT EXISTS fk_mock_payments_guest
    FOREIGN KEY (guest_id) REFERENCES guest_identities(id);
ALTER TABLE mock_payment_orders ADD CONSTRAINT IF NOT EXISTS ck_mock_payment_owner
    CHECK ((user_id IS NOT NULL AND guest_id IS NULL) OR (user_id IS NULL AND guest_id IS NOT NULL));
ALTER TABLE mock_payment_orders ADD CONSTRAINT IF NOT EXISTS uk_guest_payment_replay
    UNIQUE (guest_session_hash, event_id, guest_request_key);
ALTER TABLE mock_payment_orders ALTER COLUMN user_id DROP NOT NULL;
